// where the apps (not the web build, which the gateway serves) find mogul and auth0. these
// come from gradle.properties, local.properties (not checked in), or -P on the command line
val localProperties = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}

fun mogulProperty(name: String, default: String = ""): String =
    providers.gradleProperty(name).orNull ?: localProperties.getProperty(name) ?: default

val appConfig = mapOf(
    // the gateway, as this machine sees it. the ios simulator and the desktop app share this
    // machine's network; the android emulator reaches it at 10.0.2.2 instead (AndroidApp.kt)
    "server" to mogulProperty("mogul.server", "http://127.0.0.1:1010"),
    "auth0Domain" to mogulProperty("mogul.auth0.domain").let { if (it.isEmpty() || it.endsWith("/")) it else "$it/" },
    "auth0ClientId" to mogulProperty("mogul.auth0.clientId"),
    // the auth0 api that stands for mogul's api; the api and the gateway check tokens are for it
    "auth0Audience" to mogulProperty("mogul.auth0.audience", "https://api.mogul.tools"),
    // where auth0 sends the phone and tablet apps back to: a scheme they register
    "redirectUri" to mogulProperty("mogul.redirectUri", "com.joshlong.mogul.studio://callback"),
    // the desktop app can't register a scheme while it runs from gradle, so it listens on this
    // machine instead. this must be among the auth0 application's allowed callback URLs
    "desktopRedirectUri" to mogulProperty("mogul.desktopRedirectUri", "http://127.0.0.1:53682/callback"),
)

val generateAppConfig = tasks.register("generateAppConfig") {
    val values = appConfig
    val output = layout.buildDirectory.dir("generated/app-config/kotlin")
    inputs.properties(values)
    outputs.dir(output)
    doLast {
        fun quoted(value: String) = "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val file = output.get().file("com/joshlong/mogul/client/app/AppConfigValues.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(buildString {
            appendLine("// generated by the generateAppConfig task in shared/build.gradle.kts. don't edit")
            appendLine("package com.joshlong.mogul.client.app")
            appendLine()
            appendLine("internal val appConfig = AppConfig(")
            for ((name, value) in values) appendLine("    $name = ${quoted(value)},")
            appendLine(")")
        })
    }
}

