// oidc-appsupport's manifest needs the scheme auth0 redirects back to; the app sets it for
// real (androidApp/build.gradle.kts), this is so the library itself builds
androidComponents {
    onVariants { variant ->
        variant.manifestPlaceholders.put("oidcRedirectScheme", appConfig.getValue("redirectUri").substringBefore(":"))
    }
}

